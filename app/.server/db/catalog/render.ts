import type { CatalogEntry } from "./parse";

const HEADER = `// Generated by \`pnpm db:convert-catalog <owner's list>\` (#66). Don't edit by hand: change
// \`catalog/fixes.ts\` (or get a corrected list) and convert again.
import type { CatalogEntry } from "./catalog/parse";
`;

/** The source of `db/catalog-data.ts`; Biome formats it afterwards. */
export function renderCatalogData(entries: readonly CatalogEntry[]): string {
  const rows = entries.map((entry) => {
    // A fixed key order, so a re-conversion only shows real changes in the diff.
    const ordered: CatalogEntry = {
      publicId: entry.publicId,
      list: entry.list,
      storeCode: entry.storeCode,
      title: entry.title,
      brand: entry.brand,
      gender: entry.gender,
      fragranceFamilies: entry.fragranceFamilies,
      notes: entry.notes,
      popular: entry.popular,
    };
    return `  ${JSON.stringify(ordered)},`;
  });
  return `${HEADER}
/** The owner's perfume range, in the order of their list; \`pnpm db:import-catalog\` loads it. */
export const CATALOG_PRODUCTS: readonly CatalogEntry[] = [
${rows.join("\n")}
];
`;
}
